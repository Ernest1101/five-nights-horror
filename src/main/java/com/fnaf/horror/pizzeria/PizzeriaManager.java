/**
 * Freddy Fazbear's Pizza (FNAF 1 layout) lives in its own always-night dimension. It is built from
 * data/fnaf/structures/pizzeria.nbt the first time someone enters; posters and the animatronics are
 * placed from data/fnaf/pizzeria/markers.json (both generated by tools/pizzeria/gen_pizzeria.py).
 */
public final class PizzeriaManager {
	public static final RegistryKey<World> WORLD = RegistryKey.of(RegistryKeys.WORLD, FnafHorror.id("pizzeria"));
	public static final BlockPos ORIGIN = new BlockPos(0, 64, 0);
	private static JsonObject markers;
	/** Building size (from markers.json once loaded). The old block-built pizzeria was 66 x 9 x 58. */
	private static int sizeX = 66, sizeY = 10, sizeZ = 58;
	/** Area cleared before (re)building, covers the old block-built pizzeria too. */
	private static final int CLEAR_X = 70, CLEAR_Y = 12, CLEAR_Z = 62;

	/** Builds the pizzeria if needed, restocks the animatronics and puts the player in the security office. */
	public static boolean enter(ServerPlayerEntity player) {
		return enter(player, true);
	}

	/** freeRoam: the old free-roaming mode (animatronics hunt, flashlight); false for a FNAF night. */
	public static boolean enter(ServerPlayerEntity player, boolean freeRoam) {
		MinecraftServer server = player.getServer();
		ServerWorld world = server == null ? null : server.getWorld(WORLD);
		JsonObject m = server == null ? null : markers(server);
		if (world == null || m == null) {
			FnafHorror.LOGGER.error("Pizzeria dimension or markers missing");
			return false;
		}
		ensureBuilt(world, m);
		if (freeRoam) {
			ensureAnimatronics(world, m);
		}
		JsonArray p = m.getAsJsonArray("player");
		player.changeGameMode(GameMode.ADVENTURE);
		// a fresh, fully charged flashlight for every shift
		player.getInventory().remove(s -> s.getItem() instanceof FlashlightItem || s.isOf(com.fnaf.horror.registry.ModBlocks.GAS_CAN.asItem()), -1,
				player.playerScreenHandler.getCraftingInput());
		if (freeRoam) {
			player.getInventory().offerOrDrop(new ItemStack(ModItems.FLASHLIGHT));
		}
		player.teleport(world, ORIGIN.getX() + p.get(0).getAsDouble(), ORIGIN.getY() + p.get(1).getAsDouble(),
				ORIGIN.getZ() + p.get(2).getAsDouble(), p.get(3).getAsFloat(), 0.0f);
		player.fallDistance = 0;
		return true;
	}

	private static JsonObject markers(MinecraftServer server) {
		if (markers == null) {
			Optional<Resource> res = server.getResourceManager().getResource(FnafHorror.id("pizzeria/markers.json"));
			if (res.isEmpty()) {
				return null;
			}
			try (Reader r = new InputStreamReader(res.get().getInputStream(), StandardCharsets.UTF_8)) {
				markers = JsonParser.parseReader(r).getAsJsonObject();
				JsonArray size = markers.getAsJsonArray("size");
				sizeX = size.get(0).getAsInt();
				sizeY = size.get(1).getAsInt();
				sizeZ = size.get(2).getAsInt();
			} catch (Exception e) {
				FnafHorror.LOGGER.error("Failed to read pizzeria markers", e);
				return null;
			}
		}
		return markers;
	}

	/** /fnaf commands: "pizzeria" teleports the caller in, "rebuild" re-places the building, posters and animatronics. */
	public static void registerCommands() {
		net.fabricmc.fabric.api.event.lifecycle.v1.ServerTickEvents.END_SERVER_TICK.register(PizzeriaManager::tickAmbience);
		CommandRegistrationCallback.EVENT.register((dispatcher, registryAccess, environment) -> dispatcher.register(
				CommandManager.literal("fnaf").requires(src -> src.hasPermissionLevel(2))
						.then(CommandManager.literal("pizzeria").executes(ctx -> enter(ctx.getSource().getPlayerOrThrow()) ? 1 : 0))
						.then(CommandManager.literal("power")
								.then(CommandManager.literal("on").executes(ctx -> power(ctx.getSource().getServer(), true)))
								.then(CommandManager.literal("off").executes(ctx -> power(ctx.getSource().getServer(), false))))
						.then(CommandManager.literal("rebuild").executes(ctx -> {
							MinecraftServer server = ctx.getSource().getServer();
							ServerWorld world = server.getWorld(WORLD);
							JsonObject m = markers(server);
							if (world == null || m == null) {
								return 0;
							}
							Box all = new Box(ORIGIN, ORIGIN.add(CLEAR_X, CLEAR_Y, CLEAR_Z));
							world.getEntitiesByClass(PaintingEntity.class, all, e -> true).forEach(Entity::discard);
							world.getEntitiesByClass(AnimatronicEntity.class, all, e -> true).forEach(Entity::discard);
							build(world, m);
							ensureAnimatronics(world, m);
							ctx.getSource().sendFeedback(() -> Text.literal("Freddy Fazbear's Pizza rebuilt"), true);
							return 1;
						}))));
	}

	/** Kitchen area of the FNAF 1 layout (see gen_pizzeria.py), where Chica rattles the pots. */
	public static boolean inKitchen(World world, BlockPos pos) {
		return world.getRegistryKey() == WORLD && pos.getX() >= ORIGIN.getX() + 40 && pos.getX() <= ORIGIN.getX() + 46
				&& pos.getZ() >= ORIGIN.getZ() + 24 && pos.getZ() <= ORIGIN.getZ() + 31;
	}

	/** Background ambience for everyone inside the pizzeria, restarted when the loop (~29 s) ends. */
	public static void tickAmbience(MinecraftServer server) {
		ServerWorld world = server.getWorld(WORLD);
		if (world == null || world.getTime() % 580 != 0) {
			return;
		}
		for (ServerPlayerEntity p : world.getPlayers()) {
			p.playSound(com.fnaf.horror.registry.ModSounds.PIZZERIA_AMBIENCE, net.minecraft.sound.SoundCategory.AMBIENT, 0.7f, 1.0f);
		}
	}

	/** Everything the pizzeria ever occupied (also older, bigger versions). */
	public static Box clearBox() {
		return new Box(ORIGIN, ORIGIN.add(CLEAR_X, CLEAR_Y, CLEAR_Z));
	}

	/** Switches the pizzeria's lights directly (the generator keeps running or standing still as it was). */
	private static int power(MinecraftServer server, boolean on) {
		ServerWorld world = server.getWorld(WORLD);
		return world == null ? 0 : CeilingLightBlock.setPower(world, bounds(), on);
	}

	/** The whole building, used by the generator to switch every ceiling light. */
	public static BlockBox bounds() {
		return new BlockBox(ORIGIN.getX(), ORIGIN.getY(), ORIGIN.getZ(),
				ORIGIN.getX() + sizeX - 1, ORIGIN.getY() + sizeY - 1, ORIGIN.getZ() + sizeZ - 1);
	}

	private static Box box(JsonObject m) {
		JsonArray size = m.getAsJsonArray("size");
		return new Box(ORIGIN, ORIGIN.add(size.get(0).getAsInt(), size.get(1).getAsInt(), size.get(2).getAsInt()));
	}

	private static void ensureBuilt(ServerWorld world, JsonObject m) {
		JsonArray p = m.getAsJsonArray("player");
		BlockPos officeFloor = ORIGIN.add(p.get(0).getAsInt(), 0, p.get(2).getAsInt());
		// (re)build when nothing is there yet or an older block-built pizzeria still stands
		if (!world.getBlockState(officeFloor).isOf(com.fnaf.horror.registry.ModBlocks.MAP_BLOCK)) {
			build(world, m);
		}
	}

	private static void build(ServerWorld world, JsonObject m) {
		Optional<StructureTemplate> template = world.getStructureTemplateManager().getTemplate(FnafHorror.id("pizzeria"));
		if (template.isEmpty()) {
			FnafHorror.LOGGER.error("Missing structure fnaf:pizzeria");
			return;
		}
		// clear whatever stood here before (older pizzeria versions), then place the map cells
		net.minecraft.block.BlockState air = net.minecraft.block.Blocks.AIR.getDefaultState();
		for (BlockPos p : BlockPos.iterate(ORIGIN, ORIGIN.add(CLEAR_X, CLEAR_Y, CLEAR_Z))) {
			if (!world.getBlockState(p).isAir()) {
				world.setBlockState(p, air, Block.NOTIFY_LISTENERS | Block.FORCE_STATE | Block.SKIP_DROPS);
			}
		}
		template.get().place(world, ORIGIN, ORIGIN, new StructurePlacementData(), world.getRandom(), Block.NOTIFY_LISTENERS);
		CeilingLightBlock.setPower(world, bounds(), true);
		for (JsonElement e : m.getAsJsonArray("paintings")) {
			JsonObject o = e.getAsJsonObject();
			JsonArray pos = o.getAsJsonArray("pos");
			Optional<RegistryEntry.Reference<PaintingVariant>> variant = Registries.PAINTING_VARIANT.getEntry(
					RegistryKey.of(RegistryKeys.PAINTING_VARIANT, new Identifier(o.get("variant").getAsString())));
			Direction facing = Direction.byName(o.get("facing").getAsString());
			if (variant.isEmpty() || facing == null) {
				continue;
			}
			BlockPos at = ORIGIN.add(pos.get(0).getAsInt(), pos.get(1).getAsInt(), pos.get(2).getAsInt());
			world.spawnEntity(new PaintingEntity(world, at, facing, variant.get()));
		}
		FnafHorror.LOGGER.info("Built Freddy Fazbear's Pizza");
	}

	/** Puts the animatronics back on stage / in the cove when none are left in the building. */
	private static void ensureAnimatronics(ServerWorld world, JsonObject m) {
		if (!world.getEntitiesByClass(AnimatronicEntity.class, box(m), e -> true).isEmpty()) {
			return;
		}
		for (Map.Entry<String, JsonElement> entry : m.getAsJsonObject("animatronics").entrySet()) {
			EntityType<?> type = Registries.ENTITY_TYPE.get(FnafHorror.id(entry.getKey()));
			Entity entity = type.create(world);
			if (!(entity instanceof AnimatronicEntity animatronic)) {
				continue;
			}
			JsonArray s = entry.getValue().getAsJsonArray();
			float yaw = s.get(3).getAsFloat();
			animatronic.refreshPositionAndAngles(ORIGIN.getX() + s.get(0).getAsDouble(), ORIGIN.getY() + s.get(1).getAsDouble(),
					ORIGIN.getZ() + s.get(2).getAsDouble(), yaw, 0);
			animatronic.setHeadYaw(yaw);
			animatronic.setBodyYaw(yaw);
			animatronic.setPersistent();
			world.spawnEntity(animatronic);
		}
	}

	private PizzeriaManager() {
	}
}
